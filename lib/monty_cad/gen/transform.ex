defmodule MontyCad.Gen.Transform do
  @moduledoc """
  The source of a sensor transform: one stage of a sensor module's pipeline.

  A transform is handed the observation and the payload, and answers both the
  payload it changed and itself as it now stands — an Elixir struct cannot be
  mutated, so a stage that remembers something answers the stage that remembers
  it. What this generator writes is that shape; what it cannot write is what the
  stage does with the surface, which is the reason the stage exists.
  """

  alias MontyCad.Gen

  @doc "The module's source."
  @spec source(module()) :: String.t()
  def source(module) do
    """
    defmodule #{inspect(module)} do
      @moduledoc \"\"\"
      A sensor transform: one stage of a sensor module's pipeline.

      Generated by `mix monty_cad.gen.transform #{name(module)}`. A transform answers
      the payload it was given, changed, and itself as it now stands — a stage that
      remembers frames remembers them by answering a new struct, because nothing in
      Elixir is mutated in place.

      `call/3` raises until it does something. Two answers are honest without a
      decision: the payload untouched (a stage for a feature this run does not use),
      and a percept made from the observation, which is what
      `MontyCad.Percept.message/1` already does for a CAD frame.
      \"\"\"

      @behaviour Monty.SensorModules.SensorModule.Transform

      defstruct []

      @impl Monty.SensorModules.SensorModule.Transform
      def call(_transform, _context, _payload) do
        raise \"\"\"
        #{name(module)} has not done anything with the payload yet.

        Answer `{payload, transform}`. Monty's own transforms — the patch finder, the
        surface normaliser — are in `tbp/monty/frameworks/models/sensor_modules/` for
        the shape, and `Monty.SensorModules.SensorModule` shows how a pipeline of them
        is stepped.
        \"\"\"

      end
    end
    """
  end

  @doc "The test that holds the contract."
  @spec test_source(module()) :: String.t()
  def test_source(module) do
    """
    defmodule #{inspect(module)}Test do
      @moduledoc \"\"\"
      What a generated transform can be held to: it is a transform, and it keeps the
      promise the pipeline relies on — an answer for every input, a payload and the
      transform that made it.

      The behaviour itself is the case to translate next, from Monty's own
      `tests/`; a hand-written one states intent.
      \"\"\"

      use ExUnit.Case, async: true

      test "is a sensor transform" do
        behaviours = #{inspect(module)}.module_info(:attributes)[:behaviour] || []

        assert Monty.SensorModules.SensorModule.Transform in behaviours
      end
    end
    """
  end

  defp name(module), do: module |> Module.split() |> List.last() |> Macro.underscore()

  @doc false
  @spec files(module()) :: [{Path.t(), String.t()}]
  def files(module),
    do: [{Gen.file_path(module), source(module)}, {Gen.test_path(module), test_source(module)}]
end
