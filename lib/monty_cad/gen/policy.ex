defmodule MontyCad.Gen.Policy do
  @moduledoc """
  The source of a motor policy: the contract, the description, and nothing
  invented.

  A policy answers one question per step — where to sense next — and returns
  whether learning modules should sit the step out. What this generator writes is
  the shape of that answer and the description a cluster asks for; the decision
  itself raises until somebody writes it, because a generated function that does
  something plausible is a decision nobody made.
  """

  alias MontyCad.Gen

  @doc "The module's source."
  @spec source(module()) :: String.t()
  def source(module) do
    """
    defmodule #{inspect(module)} do
      @moduledoc \"\"\"
      A motor policy: where the sensor goes next.

      Generated by `mix monty_cad.gen.policy #{name(module)}`. What is here is the
      contract — `Monty.Frameworks.Models.MotorPolicies.MotorPolicy`'s callbacks,
      the description the cluster asks for, and a test that holds both. What is
      not here is the decision: `call/6` raises until it is written.

      It reads a part's geometry, so it is `:owner_only`: a B-rep handle cannot
      leave the node that opened it, and a policy that says `:anywhere` while
      reading one is a policy that fails the first time it is called from the
      wrong node.
      \"\"\"

      @behaviour MontyPlugin
      @behaviour Monty.Frameworks.Models.MotorPolicies.MotorPolicy

      defstruct sensor_id: "sensor_0"

      @impl MontyPlugin
      def describe do
        %{
          "name" => "#{name(module)}",
          "kind" => :motor_policy,
          "version" => "0.1.0",
          "placement" => :owner_only,
          "needs" => [:quiddity, :monty]
        }
      end

      @impl Monty.Frameworks.Models.MotorPolicies.MotorPolicy
      def call(_policy, _ctx, _observations, _state, _percept, _goal) do
        raise \"\"\"
        #{name(module)} has not decided anything yet.

        A policy answers `{MotorPolicyResult.t(), t()}`: the actions to take, whether
        learning modules sit this step out, and the policy as it now stands. Write the
        decision here — Monty's own policies are in
        `tbp/monty/frameworks/models/motor_policies.py` for the shape of an answer — and
        translate the case from Monty's `tests/` rather than inventing one.
        \"\"\"
      end

      @impl Monty.Frameworks.Models.MotorPolicies.MotorPolicy
      def reset(%__MODULE__{} = policy), do: policy

      @impl Monty.Frameworks.Models.MotorPolicies.MotorPolicy
      def state_dict(%__MODULE__{} = policy), do: %{sensor_id: policy.sensor_id}
    end
    """
  end

  @doc "The test that holds the contract, which is the part a generator can prove."
  @spec test_source(module()) :: String.t()
  def test_source(module) do
    """
    defmodule #{inspect(module)}Test do
      @moduledoc \"\"\"
      What a generated policy can be held to before it decides anything: it says
      what it is, and it is the kind of plugin it claims to be.

      The decision itself is the case to translate next. A hand-written one states
      intent; a case copied from Monty's own `tests/` is evidence, and that is
      what a policy that claims parity has to have.
      \"\"\"

      use ExUnit.Case, async: true

      alias #{inspect(module)}

      test "describes itself the way a cluster asks" do
        assert :ok = MontyPlugin.conforms?(#{alias_name(module)}.describe())
      end

      test "is a motor policy, and one that has to run where its part is" do
        description = #{alias_name(module)}.describe()

        assert description["kind"] == :motor_policy
        assert description["placement"] == :owner_only
      end

      test "forgets what it learned between episodes" do
        policy = %#{alias_name(module)}{}

        assert #{alias_name(module)}.reset(policy) == policy
        assert #{alias_name(module)}.state_dict(policy) == %{sensor_id: policy.sensor_id}
      end
    end
    """
  end

  defp name(module), do: module |> Module.split() |> List.last() |> Macro.underscore()

  defp alias_name(module), do: module |> Module.split() |> List.last()

  @doc false
  @spec files(module()) :: [{Path.t(), String.t()}]
  def files(module),
    do: [{Gen.file_path(module), source(module)}, {Gen.test_path(module), test_source(module)}]
end
